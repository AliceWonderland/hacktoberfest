# The Simplest Way
print("hello world")

# Using Variables
text = "hello world"
print(text)

# Using Conditionals
if True:
    print(text)

# Using For Loop
entry = list(text)
for i in entry:
    print(i , end = "")
print()

# Using While Loop
num = 1
while(num != 0):
    print(text)
    num -= 1

